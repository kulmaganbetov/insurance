interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
}

export async function POST(request: NextRequest) {
  try {
    const { messages } = (await request.json()) as { messages: ChatMessage[] };

    if (!Array.isArray(messages) || messages.length === 0) {
      return NextResponse.json(
        { error: 'Хабарламалар тарихы қажет' },
        { status: 400 }
      );
    }

    // If no API key, return a graceful fallback answer
    if (!process.env.OPENAI_API_KEY) {
      const lastUser = messages[messages.length - 1]?.content || '';
      return NextResponse.json({
        message: `Кешіріңіз, қазіргі уақытта AI-кеңесші қолжетімсіз (API кілті конфигурацияланбаған).\n\n**Сіздің сұрағыңыз:** "${lastUser}"\n\nТолық жауап алу үшін [калькуляторды](/calculator) пайдалануға немесе [әдіснама бетін](/about) қарауға болады.\n\n> ҚР заңнамасы бойынша нақты кеңес алу үшін лицензияланған сақтандыру компаниясына хабарласыңыз.`,
      });
    }

    const openai = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

    const completion = await openai.chat.completions.create({
      model: 'gpt-4o-mini',
      temperature: 0.4,
      max_tokens: 900,
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        ...messages.slice(-10).map((m) => ({
          role: m.role,
          content: m.content,
        })),
      ],
    });

    const answer =
      completion.choices[0]?.message?.content ||
      'Кешіріңіз, жауап ала алмадым. Қайтадан көріңіз.';

    return NextResponse.json({ message: answer });
  } catch (error) {
    console.error('Chat error:', error);
    return NextResponse.json(
      {
        error: 'AI-кеңесшімен байланыс кезінде қате орын алды',
        message:
          'Техникалық ақау орын алды. Біраздан кейін қайталап көріңіз немесе [LifeGuard KZ калькуляторын](/calculator) пайдаланыңыз.',
      },
      { status: 500 }
    );
  }
}
